// Level authoring helpers: 18-row ASCII segments joined horizontally.
export const H = 18;
export function seg(str) {
  const rows = str.replace(/^\n/, '').replace(/\n\s*$/, '').split('\n');
  const w = Math.max(...rows.map(r => r.length));
  while (rows.length < H) rows.unshift('.'.repeat(w));
  return rows.map(r => r.padEnd(w, '.'));
}
export function join(...segs) {
  const rows = []; for (let i = 0; i < H; i++) rows.push(segs.map(s => s[i] || '.'.repeat(s[0].length)).join(''));
  return rows;
}
export function level(meta, ...segs) { return { ...meta, rows: join(...segs) }; }
// repeat a segment n times
export function rep(s, n) { const out = []; for (let i = 0; i < n; i++) out.push(s); return join(...out); }

